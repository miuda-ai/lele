use std::fmt::Write;

fn main() -> lele_build::Result {
    lele_build::build_models(
        "model.toml",
        "src",
        &[
            ("encoder_model.onnx", "WhisperEncoder"),
            ("decoder_model.onnx", "WhisperDecoder"),
            ("decoder_with_past_model.onnx", "WhisperDecoderPast"),
        ],
    )?;
    write_glue()
}

/// The generated decoders take their key/value caches as one argument each, and
/// return them as tuple fields, so the code that calls them depends on how many
/// layers the model has. This writes it for the layer count in `config.json`.
fn write_glue() -> lele_build::Result {
    println!("cargo:rerun-if-changed=config.json");
    let Ok(config) = std::fs::read_to_string("config.json") else {
        // Skipped generation: nothing to count layers in.
        return Ok(());
    };
    let config: serde_json::Value = serde_json::from_str(&config)?;
    let layers = config["decoder_layers"]
        .as_u64()
        .ok_or_else(|| std::io::Error::other("config.json: no decoder_layers"))?
        as usize;

    let mut code = String::new();
    writeln!(
        code,
        "// Generated by build.rs from config.json; do not edit."
    )?;
    writeln!(code, "pub const LAYERS: usize = {layers};\n")?;

    // The first step: logits, then per layer the keys and values of the tokens
    // and of the audio.
    writeln!(
        code,
        "pub(crate) fn first_step(
    model: &WhisperDecoder<'_>,
    ws: &mut WhisperDecoderWorkspace,
    start: i64,
    hidden: &Kv,
) -> (Vec<f32>, Caches) {{
    let o = model.forward_with_workspace(
        ws,
        TensorView::from_owned(vec![start], vec![1, 1]),
        hidden.view(),
    );
    let mut caches = Caches::default();"
    )?;
    for layer in 0..layers {
        let base = 1 + 4 * layer;
        writeln!(
            code,
            "    caches.self_key.push(Kv::of(&o.{}));
    caches.self_value.push(Kv::of(&o.{}));
    caches.audio_key.push(Kv::of(&o.{}));
    caches.audio_value.push(Kv::of(&o.{}));",
            base,
            base + 1,
            base + 2,
            base + 3
        )?;
    }
    writeln!(code, "    (o.0.data.to_vec(), caches)\n}}\n")?;

    // The later steps: the caches in, the tokens' grown by one out.
    writeln!(
        code,
        "pub(crate) fn next_step(
    model: &WhisperDecoderPast<'_>,
    ws: &mut WhisperDecoderPastWorkspace,
    token: i64,
    c: &mut Caches,
) -> Vec<f32> {{
    let o = model.forward_with_workspace(
        ws,
        TensorView::from_owned(vec![token], vec![1, 1]),"
    )?;
    for layer in 0..layers {
        writeln!(
            code,
            "        c.self_key[{layer}].view(),
        c.self_value[{layer}].view(),
        c.audio_key[{layer}].view(),
        c.audio_value[{layer}].view(),"
        )?;
    }
    writeln!(code, "    );\n    let logits = o.0.data.to_vec();")?;
    writeln!(code, "    let grown: Vec<(Kv, Kv)> = vec![")?;
    for layer in 0..layers {
        writeln!(
            code,
            "        (Kv::of(&o.{}), Kv::of(&o.{})),",
            1 + 2 * layer,
            2 + 2 * layer
        )?;
    }
    writeln!(
        code,
        "    ];
    for (layer, (k, v)) in grown.into_iter().enumerate() {{
        c.self_key[layer] = k;
        c.self_value[layer] = v;
    }}
    logits
}}"
    )?;
    std::fs::write("src/glue.rs", code)?;
    Ok(())
}
